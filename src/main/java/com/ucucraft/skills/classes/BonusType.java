package com.ucucraft.skills.classes;

/**
 * Kinds of bonus a class can grant. VISUAL_CUE is an accessibility bonus:
 * it strengthens on-screen cues so players who cannot rely on sound (see the
 * rhythm minigame) can compensate through their class.
 */
public enum BonusType {
    MAX_HEALTH,
    VISUAL_CUE
}
